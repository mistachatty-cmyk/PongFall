// Imports a flags repo folder into PongFall's art registry. One command adds the whole set:
//   pnpm exec tsx scripts/import-flags.ts <path to the flag-icons package> [--starter]
// Works with the MIT-licensed `flag-icons` package (`npm pack flag-icons`, then unpack). Reads country.json and flags/4x3/*.svg,
// copies the SVGs to public/art/flags/ and writes src/core/artFlags.generated.ts (the registry reads it). ISO countries only.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const STARTER = ['us', 'gb', 'ca', 'mx', 'br', 'ar', 'fr', 'de', 'es', 'it', 'pt', 'nl', 'se', 'no', 'fi', 'pl', 'ua', 'tr', 'eg', 'za', 'ng', 'ke', 'in', 'cn', 'jp', 'kr', 'au', 'nz', 'ie', 'ch']
const dir = process.argv[2]
if (!dir) { console.error('usage: tsx scripts/import-flags.ts <flag-icons package dir> [--starter]'); process.exit(1) }
const root = resolve(dir), starter = process.argv.includes('--starter')
const countries = JSON.parse(readFileSync(join(root, 'country.json'), 'utf8')) as Array<{ code: string; name: string; continent: string | null; iso: boolean }>
const pick = countries.filter(c => c.iso && /^[a-z]{2}$/.test(c.code) && (!starter || STARTER.includes(c.code))).sort((a, b) => a.name.localeCompare(b.name))
const out = resolve(import.meta.dirname, '../public/art/flags')
rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true })
if (existsSync(join(root, 'LICENSE'))) copyFileSync(join(root, 'LICENSE'), join(out, 'LICENSE.txt'))
const rows: Array<[string, string, string]> = []
for (const c of pick) {
  const src = join(root, 'flags/4x3', `${c.code}.svg`)
  if (!existsSync(src)) continue
  copyFileSync(src, join(out, `${c.code}.svg`)); rows.push([c.code, c.name, c.continent ?? 'Other'])
}
const body = `// Generated by scripts/import-flags.ts from the MIT-licensed flag-icons set (https://github.com/lipis/flag-icons). Do not edit by hand.
export const FLAG_LICENSE = 'MIT (flag-icons, Copyright (c) 2013 Panayiotis Lipiridis)'
export const FLAG_SOURCE = 'https://github.com/lipis/flag-icons'
/** [ISO code, country name, continent] */
export const FLAGS: ReadonlyArray<readonly [string, string, string]> = ${JSON.stringify(rows)}
`
writeFileSync(resolve(import.meta.dirname, '../src/core/artFlags.generated.ts'), body)
console.log(`imported ${rows.length} flags${starter ? ' (starter set)' : ''}`)
